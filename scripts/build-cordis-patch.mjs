#!/usr/bin/env node
/**
 * Compose cordis.patch.yml for DSH 0.2.1+: registry default, host plugin, and
 * the `preset-academic-harness` / `preset-researchcraft-legacy` declarations
 * whose `config.plugins` is the contents of
 * presets/academic-harness/agent.cordis.yml. Keep that YAML as the plugin-list
 * source of truth; regenerate the patch after editing it.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dest = join(root, 'cordis.patch.yml')
const pluginsPath = join(root, 'presets', 'academic-harness', 'agent.cordis.yml')
const plugins = readFileSync(pluginsPath, 'utf8').replace(/\n$/, '')
const indented = plugins.split('\n').map((line) => (line.length ? `          ${line}` : '')).join('\n')

const preset = ({ rowId, id, name, description, order }) => `    - id: ${rowId}
      name: '@deepseek-ai/dsh-agent-preset'
      config:
        id: ${id}
        name: ${name}
        description: ${description}
        order: ${order}
        plugins:
${indented}`

const out = `# Academic Harness overlay on the web-app layer (DSH 0.2.1+).
# Default preset on agent-preset-registry, host plugin, and inline
# @deepseek-ai/dsh-agent-preset declarations. DSH 0.2.1 does not read
# $DSH_HOME/.agent-presets/. The persona is scoped by the preset's own row in
# agent.cordis.yml, not the deployment-wide system-prompt row. Regenerated by
# scripts/build-cordis-patch.mjs from presets/academic-harness/agent.cordis.yml —
# edit that file, then regenerate.
- id: agent-preset-registry
  config:
    default: academic-harness

- insert:
    - id: academic-harness
      name: academic-harness
${preset({
  rowId: 'preset-academic-harness',
  id: 'academic-harness',
  name: 'Academic Harness',
  description: 'Scientific research assistant — literature, analysis, lab notebook, and specialist subagents on DeepSeek Harness.',
  order: 0,
})}
${preset({
  rowId: 'preset-researchcraft-legacy',
  id: 'researchcraft',
  name: 'Academic Harness (legacy)',
  description: 'Legacy preset id retained for sessions created before v0.16.0. Removed in v0.17.0.',
  order: 100,
})}
`

if (process.argv.includes('--check')) {
  const current = readFileSync(dest, 'utf8')
  if (current !== out) {
    console.error('cordis.patch.yml is stale; run: node scripts/build-cordis-patch.mjs')
    process.exit(1)
  }
  process.exit(0)
}

writeFileSync(dest, out)
console.log(`wrote ${dest}`)
