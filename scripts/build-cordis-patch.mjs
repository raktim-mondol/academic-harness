#!/usr/bin/env node
/**
 * Compose cordis.patch.yml for DSH 0.2.1+: registry default, host plugin, and
 * a `preset-researchcraft` declaration whose `config.plugins` is the contents
 * of presets/researchcraft/agent.cordis.yml. Keep that YAML as the plugin-list
 * source of truth; regenerate the patch after editing it.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dest = join(root, 'cordis.patch.yml')
const pluginsPath = join(root, 'presets', 'researchcraft', 'agent.cordis.yml')
const plugins = readFileSync(pluginsPath, 'utf8').replace(/\n$/, '')
const indented = plugins.split('\n').map((line) => (line.length ? `          ${line}` : '')).join('\n')

const out = `# ResearchCraft overlay on the web-app layer (DSH 0.2.1+).
# Default preset on agent-preset-registry, host plugin, and an inline
# @deepseek-ai/dsh-agent-preset declaration. DSH 0.2.1 does not read
# $DSH_HOME/.agent-presets/. The persona is scoped by the preset's own row in
# agent.cordis.yml, not the deployment-wide system-prompt row. Regenerated by
# scripts/build-cordis-patch.mjs from presets/researchcraft/agent.cordis.yml —
# edit that file, then regenerate.
- id: agent-preset-registry
  config:
    default: researchcraft

- insert:
    - id: researchcraft
      name: dsh-researchcraft
    - id: preset-researchcraft
      name: '@deepseek-ai/dsh-agent-preset'
      config:
        id: researchcraft
        name: ResearchCraft
        description: Scientific research assistant — literature, analysis, lab notebook, and specialist subagents on DeepSeek Harness.
        order: 0
        plugins:
${indented}
`

if (process.argv.includes('--check')) {
  const current = readFileSync(dest, 'utf8')
  if (current !== out) {
    console.error('cordis.patch.yml is stale; run: node scripts/build-cordis-patch.mjs')
    process.exit(1)
  }
  process.exit(0)
}

writeFileSync(dest, out)
console.log(`wrote ${dest}`)
