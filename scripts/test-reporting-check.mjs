/**
 * reporting_check acceptance tests.
 *
 * Covers the Phase 3 acceptance criteria: fabricated quotes rejected,
 * verified quotes accepted across Markdown/LaTeX/DOCX, stale evidence after an
 * edit, not_reported without searched rejected, export ids matching the
 * checklist, suggest never selecting, and no compliance label in exports.
 * Plus registration, aliases, candidate ranking, override rules, workspace
 * confinement, PaperMemory chunk input, and the notebook hand-off.
 */
import assert from 'node:assert/strict'
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import AdmZip from 'adm-zip'
import {
  apply, loadGuidelines, maskLatex, resolveChecklist, runReportingCheck,
  suggestGuidelines,
} from '../reporting-check.js'
import { readVerdicts } from '../reporting-store.js'
import { runHelper } from '../python-runtime.js'

const root = process.cwd()
const registered = () => {
  const names = []
  apply({ tools: { register: (tool) => names.push(tool.name) } })
  return names
}
assert.deepEqual(registered(), ['reporting_check'], 'reporting_check must register one tool')
assert.match(readFileSync(join(root, 'reporting-check.js'), 'utf8'), /export const inject = \['tools'\]/)

/* --------------------------------------------------------------- checklists */

const guidelines = loadGuidelines()
assert.equal(guidelines.length, 9, 'nine checklists ship in the first set')
const expected = {
  consort: [2010, 38], strobe: [2007, 34], prisma: [2020, 44], 'prisma-s': [2021, 16],
  'prisma-scr': [2018, 22], arrive: ['2.0', 25], 'tripod-ai': [2024, 27], care: [2013, 31], stard: [2015, 30],
}
for (const guideline of guidelines) {
  const [version, count] = expected[guideline.id]
  assert.equal(String(guideline.version), String(version), `${guideline.id} version`)
  assert.equal(guideline.items.length, count, `${guideline.id} item count`)
  const ids = guideline.items.map((item) => item.id)
  assert.equal(new Set(ids).size, ids.length, `${guideline.id} item ids are unique`)
  for (const item of guideline.items) {
    assert.ok(item.section && item.short_prompt && item.cues?.length, `${guideline.id}/${item.id} is complete`)
    assert.equal(item.source_url, guideline.source_url, `${guideline.id}/${item.id} source link`)
  }
  assert.ok(guideline.source_url.startsWith('https://'), `${guideline.id} has an official source link`)
}
assert.equal(resolveChecklist('CONSORT').id, 'consort')
assert.equal(resolveChecklist('consort-2010').id, 'consort')
assert.equal(resolveChecklist('PRISMA 2020').id, 'prisma')
assert.equal(resolveChecklist('PRISMA-S').id, 'prisma-s')
assert.equal(resolveChecklist('PRISMA-ScR').id, 'prisma-scr')
assert.equal(resolveChecklist('ARRIVE 2.0').id, 'arrive')
assert.equal(resolveChecklist('TRIPOD+AI').id, 'tripod-ai')
assert.equal(resolveChecklist('CARE').id, 'care')
assert.equal(resolveChecklist('STARD').id, 'stard')
assert.throws(() => resolveChecklist('made-up-guideline'), /unknown guideline/)

/* ------------------------------------------------------------------ fixtures */

const cwd = mkdtempSync(join(tmpdir(), 'ah-reporting-'))
const exec = {
  agent: { session: { header: { cwd, id: 'reporting-test-session' } } },
  callId: 'call-reporting',
}
const markdownPath = join(cwd, 'paper.md')
const markdown = `# A randomised trial of X

## Abstract

This structured abstract summarises a randomised controlled trial including methods and conclusions.

## Introduction

The background and rationale are that X may improve Y.

## Methods

Participants were randomly assigned to intervention or control groups. The allocation sequence was generated by a computer random-number generator. Allocation was concealed using sequentially numbered opaque envelopes. Nurses enrolled participants and assigned them to groups. The primary outcome was change in Y at 12 weeks.

## Results

Participant flow is shown in Figure 1. Two participants were lost to follow-up. The primary outcome improved by 20% (95% CI 10 to 30), and the effect size was consistent.

## Discussion

Limitations include a single centre. The findings are consistent with prior work and may not generalise.

## Other information

Trial registration: NCT01234567. Funding: a public grant. The protocol is available online.
`
writeFileSync(markdownPath, markdown)

const latexPath = join(cwd, 'paper.tex')
const latex = String.raw`\documentclass{article}
\title{A randomised trial of X}
\begin{document}
\section{Methods}
%% @unit trial.p001  h=abc123
Participants were \textbf{randomly assigned} to intervention or control groups. The allocation was concealed using sequentially numbered opaque envelopes.
\section{Results}
The primary outcome improved by 20\% (95\% CI 10--30).
\end{document}
`
writeFileSync(latexPath, latex)
assert.equal(maskLatex(latex).length, latex.length, 'LaTeX masking preserves offsets')
assert.equal(maskLatex(latex).split('\n').length, latex.split('\n').length, 'LaTeX masking preserves lines')
assert.match(maskLatex(latex), /Participants were\s+randomly assigned/, 'LaTeX masking keeps prose')
assert.doesNotMatch(maskLatex(latex), /\\textbf/, 'LaTeX masking removes commands')

const docxPath = join(cwd, 'paper.docx')
const zip = new AdmZip()
zip.addFile('word/document.xml', Buffer.from(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>
<w:p><w:pPr><w:pStyle w:val="Heading1"/></w:pPr><w:r><w:t>Methods</w:t></w:r></w:p>
<w:p><w:r><w:t>Participants were randomly assigned to intervention or control groups.</w:t></w:r></w:p>
<w:p><w:r><w:t>The allocation was concealed with sequentially numbered opaque envelopes.</w:t></w:r></w:p>
</w:body></w:document>`))
zip.writeZip(docxPath)

