/* --------------------------------------------------------------------- start */

{
  const started = await runReportingCheck({ action: 'start', slug: 'md-check', guideline: 'consort', manuscript: 'paper.md' }, exec)
  assert.equal(started.resumed, false)
  assert.equal(started.check.guideline.name, 'CONSORT 2010')
  assert.equal(started.check.item_ids.length, 38)
  assert.match(started.check.manuscript.sha256, /^[a-f0-9]{64}$/)
  assert.equal(started.check.manuscript.title, 'A randomised trial of X')
  await assert.rejects(
    () => runReportingCheck({ action: 'start', slug: 'md-check', guideline: 'consort', manuscript: 'paper.md' }, exec),
    /already exists/,
  )
  const resumed = await runReportingCheck({ action: 'start', slug: 'md-check', resume: true }, exec)
  assert.equal(resumed.resumed, true)
  await assert.rejects(
    () => runReportingCheck({ action: 'start', slug: 'md-check', guideline: 'strobe', manuscript: 'paper.md', resume: true }, exec),
    /cannot be resumed/,
  )
  await assert.rejects(
    () => runReportingCheck({ action: 'start', slug: 'bad', guideline: 'consort', manuscript: '../outside.md' }, exec),
    /escapes the workspace/,
  )
  writeFileSync(join(cwd, 'bad.xyz'), 'text')
  await assert.rejects(
    () => runReportingCheck({ action: 'start', slug: 'bad', guideline: 'consort', manuscript: 'bad.xyz' }, exec),
    /unsupported manuscript type/,
  )
  assert.ok(existsSync(join(cwd, '.dsh', 'notebook', 'reporting-test-session.jsonl')), 'start logs to the notebook')
  assert.match(readFileSync(join(cwd, '.dsh', 'notebook', 'reporting-test-session.jsonl'), 'utf8'), /Reporting check started/)
}

/* --------------------------------------------------------------- items/candidates */

