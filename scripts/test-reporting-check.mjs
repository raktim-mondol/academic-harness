const suggestionSource = {
  text: markdown.toLowerCase(),
  rawText: markdown,
}
const suggestion = suggestGuidelines(suggestionSource)
assert.equal(suggestion.suggestions[0].id, 'consort', 'randomised trial suggests CONSORT first')
assert.ok(suggestion.suggestions[0].matching_terms.length > 0)
assert.ok(!('selected' in suggestion), 'suggest never selects a guideline')
assert.match(suggestion.note, /never selected|No guideline was selected/i)
for (const [text, id] of [
  ['We conducted a systematic review and meta-analysis with a search strategy across PubMed.', 'prisma'],
  ['This scoping review maps the evidence.', 'prisma-scr'],
  ['Mice were housed under a 12-hour light cycle; the IACUC approved the protocol.', 'arrive'],
  ['A machine learning prediction model was trained; we report AUC and calibration.', 'tripod-ai'],
  ['We report a case of a 42-year-old man with an unusual presentation.', 'care'],
  ['A diagnostic accuracy study compared the index test with a reference standard for sensitivity and specificity.', 'stard'],
  ['A prospective cohort study examined confounders and observed participants.', 'strobe'],
]) {
  const picked = suggestGuidelines({ text: text.toLowerCase(), rawText: text }).suggestions.map((entry) => entry.id)
  assert.ok(picked.includes(id), `${id} should be suggested for: ${text}`)
}

