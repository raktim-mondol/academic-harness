#!/usr/bin/env node
/**
 * Normalise the `license:` frontmatter of the bundled skills to SPDX identifiers.
 *
 *   node scripts/normalize-skill-licenses.mjs --check            # exit 1 if a mappable label is not yet SPDX
 *   node scripts/normalize-skill-licenses.mjs --write            # rewrite those labels in place
 *   node scripts/normalize-skill-licenses.mjs --report FILE.md   # write the owner's inventory
 *
 * Only labels with an unambiguous meaning are rewritten (see skill-licenses.js).
 * Everything else is listed as unresolved with a reason and left untouched:
 * GPL labels that name a library's licence, links, "Unknown", free text and
 * skills with no label. Those need a decision from the owner, not a guess.
 * Only the `license:` line inside the frontmatter is edited.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { isNonCommercial, normalize, readLicense } from '../skill-licenses.js'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SKILLS = join(ROOT, 'skills')
const args = process.argv.slice(2)
const write = args.includes('--write')
const reportIndex = args.indexOf('--report')
const reportFile = reportIndex === -1 ? null : args[reportIndex + 1]

const rows = []
for (const name of readdirSync(SKILLS).sort()) {
  let text
  try {
    text = readFileSync(join(SKILLS, name, 'SKILL.md'), 'utf8')
  } catch {
    continue
  }
  const raw = readLicense(text)
  const result = normalize(raw)
  rows.push({ name, raw, result, text })
}

const toChange = rows.filter((r) => r.result.spdx && r.result.changed)
if (write) {
  for (const r of toChange) {
    const updated = r.text.replace(/^(---\r?\n[\s\S]*?^license:[ \t]*).*$/m, (_, head) => `${head}${r.result.spdx}`)
    writeFileSync(join(SKILLS, r.name, 'SKILL.md'), updated)
  }
  console.log(`rewrote ${toChange.length} license label(s) to SPDX identifiers`)
}

const unresolved = rows.filter((r) => r.result.unresolved)
const byReason = new Map()
for (const r of unresolved) {
  const list = byReason.get(r.result.unresolved) ?? []
  list.push(r)
  byReason.set(r.result.unresolved, list)
}
const counts = new Map()
for (const r of rows) if (r.result.spdx) counts.set(r.result.spdx, (counts.get(r.result.spdx) ?? 0) + 1)

console.log(`${rows.length} skills: ${[...counts].map(([k, v]) => `${v} ${k}`).join(', ')}; ${unresolved.length} unresolved`)
if (!write) console.log(`${toChange.length} label(s) not yet in SPDX form`)

if (reportFile) {
  const lines = [
    '# Skill licence inventory',
    '',
    'Generated by `node scripts/normalize-skill-licenses.mjs --report`. Skills whose label has an unambiguous SPDX form are rewritten by `--write`. The rest are listed here for the owner; the script never guesses a licence.',
    '',
    '## Resolved',
    '',
    '| SPDX identifier | Skills |',
    '|---|---|',
    ...[...counts].sort().map(([k, v]) => `| ${k} | ${v} |`),
    '',
    `Non-commercial (excluded by \`AH_EXCLUDE_NONCOMMERCIAL=1\` and \`npm run pack:commercial\`): ${rows.filter((r) => isNonCommercial(r.result.spdx ?? r.raw)).map((r) => `\`${r.name}\``).join(', ')}.`,
    '',
    `## Unresolved (${unresolved.length})`,
    '',
  ]
  for (const [reason, list] of [...byReason].sort((a, b) => b[1].length - a[1].length)) {
    lines.push(`### ${reason} (${list.length})`, '')
    for (const r of list) lines.push(`- \`${r.name}\`${r.raw ? `: \`${r.raw.length > 90 ? `${r.raw.slice(0, 90)}…` : r.raw}\`` : ''}`)
    lines.push('')
  }
  writeFileSync(reportFile, `${lines.join('\n')}\n`)
  console.log(`wrote ${reportFile}`)
}

if (!write && toChange.length > 0) {
  console.error(`FAIL  ${toChange.length} skill(s) use a non-SPDX spelling of a known licence, e.g. ${toChange.slice(0, 3).map((r) => `${r.name}: "${r.raw}"`).join('; ')}. Run with --write.`)
  process.exit(1)
}
